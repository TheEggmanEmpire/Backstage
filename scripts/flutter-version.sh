#!/usr/bin/env bash
# Single source of truth for the toolchain = what upstream's own CI uses.
#   --print: show the pins derived from upstream/dextop
#   --sync : rewrite toolchain.env from them (run by update-upstream.sh)
#   --check: fail if toolchain.env disagrees (run in CI before building)
. "$(dirname "$0")/lib.sh"
wf=$UPSTREAM_DIR/.github/workflows/debug-apk.yml
[ -f "$wf" ] || die "upstream CI workflow missing: ${wf#$ROOT/} (upstream restructured? update scripts/flutter-version.sh)"
yaml() { sed -n "s/^[[:space:]]*$1:[[:space:]]*[\"']\{0,1\}\([^\"'[:space:]]*\)[\"']\{0,1\}[[:space:]]*$/\1/p" "$wf" | head -1; }
kts()  { sed -n "s/.*id(\"$1\") version \"\([^\"]*\)\".*/\1/p" "$UPSTREAM_DIR/android/settings.gradle.kts" | head -1; }
derived() {
  echo "FLUTTER_VERSION=$(yaml flutter-version)"
  echo "FLUTTER_CHANNEL=$(yaml channel)"
  echo "JAVA_VERSION=$(yaml java-version)"
  echo "AGP_VERSION=$(kts com.android.application)"
  echo "KOTLIN_VERSION=$(kts org.jetbrains.kotlin.android)"
  echo "CMAKE_VERSION=$(sed -n 's/^[[:space:]]*version = "\([0-9.]*\)".*/\1/p' "$UPSTREAM_DIR/android/app/build.gradle.kts" | head -1)"
  echo "GRADLE_DIST=$(sed -n 's#^distributionUrl=.*/\(gradle-[^/]*\)$#\1#p' "$UPSTREAM_DIR/android/gradle/wrapper/gradle-wrapper.properties")"
  echo "DART_SDK_CONSTRAINT='$(sed -n 's/^[[:space:]]*sdk:[[:space:]]*\(.*\)$/\1/p' "$UPSTREAM_DIR/pubspec.yaml" | head -1)'"
  # compileSdk / targetSdk / NDK are NOT in upstream files: android/app/build.gradle.kts reads
  # flutter.compileSdkVersion / flutter.ndkVersion, i.e. they follow the Flutter SDK version above
  # (3.47.7: compileSdk 36, targetSdk 36, NDK 28.2.13676358).
}
out=$TOOLCHAIN_ENV
case "${1:---print}" in
  --print) derived ;;
  --sync)  { echo "# generated by scripts/flutter-version.sh from upstream $UPSTREAM_REF; do not edit"; derived; } > "$out"; cat "$out" ;;
  --check) [ -f "$out" ] || die "toolchain.env missing; run scripts/flutter-version.sh --sync"
           diff <(derived) <(grep -v '^#' "$out") >/dev/null || {
             echo "toolchain.env is stale vs upstream; run scripts/flutter-version.sh --sync" >&2
             diff <(derived) <(grep -v '^#' "$out") >&2; exit 1; }
           echo "OK: toolchain.env matches upstream $UPSTREAM_REF ($(grep '^FLUTTER_VERSION=' "$out"))" ;;
  *) die "usage: $0 [--print|--sync|--check]" ;;
esac
