#!/usr/bin/env python3
"""Backstage icon "Layer Peek" (owner's pick #1, candidate 09): a phone in front, the desktop window running behind it.

One geometry source -> Android vector drawables + PNG renders. Coordinates are in the 108x108 adaptive-icon space; the
composition is scaled about its centre so every point stays inside the 66 dp safe circle (radius 33 around 54,54).
"""
import math, os, sys
from PIL import Image, ImageDraw

OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "out")

BG = "#3E4C63"      # slate: the dark "backstage" behind the phone
WIN = "#FFA51F"     # amber: the desktop, alive and running
PHONE = "#FFFFFF"   # white: the phone you hold

# Composition in source units (traced from the chosen raster, 1254 px canvas -> 108), then scaled about its centre.
S, CX, CY = 0.78, 53.75, 54.0
def T(x, y): return (54 + (x - CX) * S, 54 + (y - CY) * S)
def L(v): return v * S

WINDOW = (34.6, 20.8, 81.6, 60.6, 4.0)          # x0, y0, x1, y1, radius
TITLE_GAP = (28.4, 30.5)                        # y band cut through the window (title bar separator)
DOTS = [(64.7, 24.9), (70.3, 24.9), (75.9, 24.9)]
DOT_R = 1.75
PHONE_OUT = (25.9, 32.0, 61.1, 87.2, 7.0)
PHONE_IN = (29.5, 35.6, 57.5, 83.6, 4.3)
GAP = 1.6  # monochrome: clearance between phone and window so the two planes stay separate in one colour

def f(v): return f"{v:.2f}".rstrip("0").rstrip(".")

def rrect_path(x0, y0, x1, y1, r):
    (x0, y0), (x1, y1), r = T(x0, y0), T(x1, y1), L(r)
    return (f"M{f(x0+r)},{f(y0)}H{f(x1-r)}A{f(r)},{f(r)} 0,0 1,{f(x1)},{f(y0+r)}V{f(y1-r)}"
            f"A{f(r)},{f(r)} 0,0 1,{f(x1-r)},{f(y1)}H{f(x0+r)}A{f(r)},{f(r)} 0,0 1,{f(x0)},{f(y1-r)}"
            f"V{f(y0+r)}A{f(r)},{f(r)} 0,0 1,{f(x0+r)},{f(y0)}Z")

def circle_path(cx, cy, r):
    (cx, cy), r = T(cx, cy), L(r)
    return f"M{f(cx-r)},{f(cy)}A{f(r)},{f(r)} 0,1 1,{f(cx+r)},{f(cy)}A{f(r)},{f(r)} 0,1 1,{f(cx-r)},{f(cy)}Z"

def rect_path(x0, y0, x1, y1):
    (x0, y0), (x1, y1) = T(x0, y0), T(x1, y1)
    return f"M{f(x0)},{f(y0)}H{f(x1)}V{f(y1)}H{f(x0)}Z"

def window_body():
    """Window minus title gap and dots (evenOdd holes)."""
    x0, y0, x1, y1, r = WINDOW
    holes = rect_path(x0, TITLE_GAP[0], x1, TITLE_GAP[1]) + "".join(circle_path(x, y, DOT_R) for x, y in DOTS)
    return rrect_path(*WINDOW) + holes

def phone_ring():
    return rrect_path(*PHONE_OUT) + rrect_path(*PHONE_IN)

def window_clip_mono():
    """Union of the window parts not covered by the phone (plus GAP clearance): right of it and above it."""
    x0, y0, x1, y1, _ = PHONE_OUT
    return rect_path(x1 + GAP, -50, 200, 200) + rect_path(-50, -50, 200, y0 - GAP)

HDR = '<?xml version="1.0" encoding="utf-8"?>\n'
def vector(body, w=108, h=108, vw=108, vh=108, comment=""):
    c = f"<!-- {comment} -->\n" if comment else ""
    return (HDR + c + f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{w}dp"\n    android:height="{h}dp"\n'
            f'    android:viewportWidth="{vw}"\n    android:viewportHeight="{vh}">\n{body}</vector>\n')

def p(color, data, even=False, indent="    "):
    fill = f'\n{indent}    android:fillType="evenOdd"' if even else ""
    return f'{indent}<path\n{indent}    android:fillColor="{color}"{fill}\n{indent}    android:pathData="{data}" />\n'

def argb(c): return "#FF" + c[1:].upper()

COMMENT = ('Backstage icon "Layer Peek" (original artwork, generated by gen_icon.py): the phone in front, the desktop '
           'running behind it.')

def color_fg(indent="    "):
    return (p(argb(WIN), window_body(), True, indent)
            + p(argb(BG), rrect_path(*PHONE_OUT), False, indent)      # the phone hides what is behind it
            + p(argb(PHONE), phone_ring(), True, indent))

def mono_body(color="#FF000000", indent="    "):
    return (f'{indent}<group>\n{indent}    <clip-path android:pathData="{window_clip_mono()}" />\n'
            + p(color, window_body(), True, indent + "    ") + f"{indent}</group>\n"
            + p(color, phone_ring(), True, indent))

def write(rel, text):
    path = os.path.join(OUT, rel); os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(text)

# ------------------------------------------------------------------------------------------------ vectors
write("res/drawable/bs_ic_launcher_bg.xml", vector(p(argb(BG), "M0,0H108V108H0Z"), comment=COMMENT))
write("res/drawable/bs_ic_launcher_fg.xml", vector(color_fg(), comment=COMMENT))
write("res/drawable/bs_ic_launcher_mono.xml", vector(mono_body(), comment=COMMENT + " Monochrome (themed icon) layer."))
round_body = ('    <group android:translateX="-18" android:translateY="-18">\n'
              + p(argb(BG), "M54,18A36,36 0,1 1,54 90A36,36 0,1 1,54 18Z", False, "        ")
              + color_fg("        ") + "    </group>\n")
write("res/drawable/bs_ic_launcher_round.xml",
      vector(round_body, 48, 48, 72, 72, COMMENT + " Round rendition: the adaptive layers cut to the 72 dp circle."))
# Status-bar / Quick Settings / notification glyph: white monochrome on 24 dp (system tints it).
# 108 -> 24 viewport: content spans ~27..81 (54 units); scale 32/108 then shift so it fills ~2..22.
GLYPH_SCALE = 24 / 60.0
glyph = (f'    <group android:scaleX="{GLYPH_SCALE:.4f}" android:scaleY="{GLYPH_SCALE:.4f}" '
         f'android:translateX="{12 - 54 * GLYPH_SCALE:.3f}" android:translateY="{12 - 54 * GLYPH_SCALE:.3f}">\n'
         + mono_body("#FFFFFFFF", "        ") + "    </group>\n")
write("res/drawable/bs_ic_glyph.xml", vector(glyph, 24, 24, 24, 24, COMMENT + " 24 dp white glyph (tinted by the system)."))

# "Start desktop" launcher shortcut (adaptive): the desktop window alone with a play mark in its body.
def shortcut_fg():
    x0, y0, x1, y1, r = WINDOW
    # centre the window on its own in the safe zone: shift so its centre is at (54,54) before the global transform.
    dx, dy = (CX - (x0 + x1) / 2), (CY - (y0 + y1) / 2)
    def sh(t): return (t[0] + dx, t[1] + dy, t[2] + dx, t[3] + dy, t[4])
    win = sh(WINDOW)
    holes = rect_path(win[0], TITLE_GAP[0] + dy, win[2], TITLE_GAP[1] + dy) + "".join(
        circle_path(x + dx, y + dy, DOT_R) for x, y in DOTS)
    # play triangle in the window body, cut out (evenOdd hole) so the background shows through.
    bx, by = (win[0] + win[2]) / 2, (TITLE_GAP[1] + dy + win[3]) / 2
    a, b = T(bx - 4.5, by - 6.5), T(bx - 4.5, by + 6.5)
    c = T(bx + 7.0, by)
    tri = f"M{f(a[0])},{f(a[1])}L{f(c[0])},{f(c[1])}L{f(b[0])},{f(b[1])}Z"
    return p(argb(WIN), rrect_path(*win) + holes + tri, True)
write("res/drawable/ic_shortcut_dextop_foreground.xml", vector(shortcut_fg(), comment=COMMENT + ' "Start desktop" shortcut foreground.'))
write("res/drawable/ic_shortcut_dextop.xml", HDR + f"<!-- {COMMENT} \"Start desktop\" shortcut. -->\n"
      '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
      '    <background android:drawable="@drawable/bs_ic_launcher_bg" />\n'
      '    <foreground android:drawable="@drawable/ic_shortcut_dextop_foreground" />\n'
      '</adaptive-icon>\n')
# Quick Settings: main tile = the Backstage glyph; "display" tile = the desktop window outline glyph.
write("res/drawable/ic_qs_dextop.xml", HDR + f"<!-- {COMMENT} Quick Settings / notification glyph. -->\n"
      '<inset xmlns:android="http://schemas.android.com/apk/res/android" android:drawable="@drawable/bs_ic_glyph" />\n')
disp = ('<path android:fillColor="#FFFFFFFF" android:fillType="evenOdd" android:pathData="'
        'M4,4.5h16a2,2 0 0 1 2,2v11a2,2 0 0 1-2,2H4a2,2 0 0 1-2-2v-11a2,2 0 0 1 2-2Z'
        'M3.8,9.2v8.3a.7,.7 0 0 0 .7,.7h15a.7,.7 0 0 0 .7-.7V9.2Z'
        'M14.6,6.85a.85,.85 0 1 0 1.7,0a.85,.85 0 1 0-1.7,0Z'
        'M17.2,6.85a.85,.85 0 1 0 1.7,0a.85,.85 0 1 0-1.7,0Z" />\n')
write("res/drawable/ic_qs_dextop_display.xml",
      vector("    " + disp, 24, 24, 24, 24, COMMENT + " Quick Settings display tile: the desktop window."))

# ------------------------------------------------------------------------------------------------ rasters
def hexrgb(c): return tuple(int(c[i:i + 2], 16) for i in (1, 3, 5))

def render(px, shape="square", bg=True, full_bleed=False):
    ss = 4; n = px * ss
    img = Image.new("RGBA", (n, n), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    # full_bleed (Play store / Flutter asset): the 108 canvas scaled so the safe zone fills more of the square.
    view = 108.0 if not full_bleed else 80.0
    off = (108.0 - view) / 2
    k = n / view
    def P(x, y): X, Y = T(x, y); return ((X - off) * k, (Y - off) * k)
    def rr(spec, fill):
        x0, y0, x1, y1, r = spec
        a, b = P(x0, y0), P(x1, y1)
        d.rounded_rectangle([a, b], radius=L(r) * k, fill=fill)
    if bg:
        if shape == "circle": d.ellipse([0, 0, n - 1, n - 1], fill=hexrgb(BG))
        elif shape == "squircle": d.rounded_rectangle([0, 0, n - 1, n - 1], radius=n * 0.22, fill=hexrgb(BG))
        else: d.rectangle([0, 0, n, n], fill=hexrgb(BG))
    rr(WINDOW, hexrgb(WIN))
    a, b = P(WINDOW[0], TITLE_GAP[0]), P(WINDOW[2], TITLE_GAP[1])
    d.rectangle([a, b], fill=hexrgb(BG))
    for x, y in DOTS:
        cx, cy = P(x, y); r = L(DOT_R) * k
        d.ellipse([cx - r, cy - r, cx + r, cy + r], fill=hexrgb(BG))
    rr(PHONE_OUT, hexrgb(PHONE)); rr(PHONE_IN, hexrgb(BG))
    if shape == "circle" and bg:  # keep the window's notch area inside the circle clean
        mask = Image.new("L", (n, n), 0); ImageDraw.Draw(mask).ellipse([0, 0, n - 1, n - 1], fill=255)
        img.putalpha(Image.composite(img.getchannel("A"), Image.new("L", (n, n), 0), mask))
    return img.resize((px, px), Image.LANCZOS)

DENS = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
for dpi, px in DENS.items():
    # Legacy (pre-adaptive) launcher PNGs: shown for the.apk file icon by PC tools / file managers.
    os.makedirs(os.path.join(OUT, f"res/mipmap-{dpi}"), exist_ok=True)
    render(px, "squircle", full_bleed=True).save(os.path.join(OUT, f"res/mipmap-{dpi}/bs_ic_launcher.png"), optimize=True)
os.makedirs(os.path.join(OUT, "play"), exist_ok=True)
render(512, "square", full_bleed=True).save(os.path.join(OUT, "play/play-store-icon-512.png"), optimize=True)
os.makedirs(os.path.join(OUT, "flutter"), exist_ok=True)
render(512, "squircle", full_bleed=True).save(os.path.join(OUT, "flutter/backstage_icon.png"), optimize=True)
# Preview sheet: adaptive circle, squircle, 48/24 px, glyph-ish monochrome stand-in.
sheet = Image.new("RGBA", (1100, 300), (24, 24, 24, 255))
x = 20
for img in [render(256, "circle"), render(256, "squircle", full_bleed=True), render(96, "circle"), render(48, "circle"), render(24, "circle")]:
    sheet.alpha_composite(img, (x, 20 + (256 - img.height) // 2)); x += img.width + 30
sheet.save(os.path.join(OUT, "preview.png"))
print("wrote", OUT)
