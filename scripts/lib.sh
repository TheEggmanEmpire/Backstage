# shellcheck shell=bash
# Shared settings + helpers for scripts/*.sh. Sourced, not executed.
#
# Upstream integration model:
#   upstream/dextop     pristine snapshot of UPSTREAM_COMMIT, never edited (tree-hash guard)
#   upstream/UPSTREAM.env   provenance: URL, REF (git describe), COMMIT, TREE, DATE, VERSION
#   patches/NNNN-*.patch    git format-patch series, in-file behaviour only, applied strictly in name order
#   patches/.rr-cache       committed git-rerere resolutions replayed by update-upstream.sh
#   scripts/inject.sh       the two Gradle entry-point hooks (idempotent one-line injections, not diffs)
#   toolchain.env           Flutter/Java/AGP/KGP/CMake/Gradle pins derived from upstream (flutter-version.sh)
set -euo pipefail
export LC_ALL=C

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)
UPSTREAM_DIR=$ROOT/upstream/dextop                 # pristine snapshot, never edited by hand
UPSTREAM_ENV=$ROOT/upstream/UPSTREAM.env           # provenance
PATCH_DIR=$ROOT/patches                            # git format-patch series, applied in name order
TOOLCHAIN_ENV=$ROOT/toolchain.env                  # generated by scripts/flutter-version.sh --sync
CACHE=${BACKSTAGE_CACHE:-$ROOT/.cache}/dextop.git  # full-history upstream mirror (gitignored)
WORK=${BACKSTAGE_WORK:-$ROOT/build/work/dextop}    # patched tree that Flutter/Gradle build (own nested git repo)
DIST=$ROOT/dist
BOT=(-c user.name="Backstage patch bot" -c user.email="patches@backstage.invalid" -c commit.gpgsign=false
     -c core.autocrlf=false -c advice.detachedHead=false)
# shellcheck disable=SC1090
. "$UPSTREAM_ENV"

log()  { printf '[%s %s] %s\n' "$(basename "$0" .sh)" "$(date +%H:%M:%S)" "$*" >&2; }
warn() { printf '[%s %s] WARNING: %s\n' "$(basename "$0" .sh)" "$(date +%H:%M:%S)" "$*" >&2; }
die()  { printf '[%s %s] ERROR: %s\n' "$(basename "$0" .sh)" "$(date +%H:%M:%S)" "$*" >&2; exit 1; }

# One path per line. Never word-split it (`for p in $(patches)`): checkout paths may contain spaces. Read it with
# `mapfile -t ps < <(patches)` and use "${ps[@]}".
patches() { find "$PATCH_DIR" -maxdepth 1 -name '[0-9][0-9][0-9][0-9]-*.patch' | LC_ALL=C sort; }

# Identity of what a work tree is prepared from: pinned snapshot + patch series + hook injector.
# prepare-work-tree.sh records it as `git config backstage.prepared` only after EVERY step succeeded.
series_key() {
  local ps p
  mapfile -t ps < <(patches)
  { echo "$UPSTREAM_TREE"; for p in "${ps[@]}"; do cat "$p"; done; cat "$ROOT/scripts/inject.sh"; } | sha256sum | cut -c1-16
}

# Fail unless $WORK is completely prepared from the CURRENT series (build/test steps run with --no-prepare
# must never build a stale or half-patched tree).
require_prepared() {
  [ -d "$WORK/.git" ] || die "$WORK is not prepared (run scripts/prepare-work-tree.sh)"
  [ "$(git -C "$WORK" config --get backstage.prepared 2>/dev/null || true)" = "$(series_key)" ] ||
    die "$WORK is not prepared from the current upstream pin + patches/ (run scripts/prepare-work-tree.sh)"
  "$ROOT/scripts/inject.sh" --check "$WORK" 2>/dev/null ||
    die "$WORK lacks the Gradle hooks for this checkout ($ROOT): reset by hand or prepared by another checkout (run scripts/prepare-work-tree.sh)"
}

# prepare-work-tree.sh resets $WORK with `git checkout -f`/`reset --hard`: refuse any directory that is not a
# dedicated work tree (/, $HOME, the repository or an ancestor of it, a non-empty foreign directory).
guard_work_dir() {
  local dir home
  dir=$(realpath -m -- "$1"); home=$(realpath -m -- "${HOME:-/}")
  { [ "$dir" = / ] || [ "$dir" = "$home" ]; } && die "refusing work tree $dir (BACKSTAGE_WORK must be a dedicated directory)"
  case "$ROOT/" in "$dir"/*) die "refusing work tree $dir: it contains the Backstage repository $ROOT" ;; esac
  [ -d "$dir" ] && [ -n "$(ls -A -- "$dir" 2>/dev/null)" ] || return 0
  if [ -d "$dir/.git" ] && { [ -n "$(git -C "$dir" config --get backstage.work 2>/dev/null)" ] ||
       git -C "$dir" rev-parse -q --verify refs/tags/upstream >/dev/null 2>&1; }; then
    return 0
  fi
  die "refusing non-empty $dir: not a work tree made by scripts/prepare-work-tree.sh (empty it or choose another BACKSTAGE_WORK)"
}

# Full-history bare mirror: 3-way merges in update-upstream.sh need the old blobs (~63 MB).
ensure_cache() {
  local attempt
  if [ ! -d "$CACHE" ]; then
    mkdir -p "$(dirname "$CACHE")"
    for attempt in 1 2 3; do
      git clone -q --bare "$UPSTREAM_URL" "$CACHE" && break
      rm -rf "$CACHE"; warn "clone failed (attempt $attempt)"; sleep $((attempt * 5))
    done
    [ -d "$CACHE" ] || die "could not clone $UPSTREAM_URL"
  fi
  # upstream/dextop must be byte-identical to the commit tree (UPSTREAM_TREE drift guard): `git archive` would
  # otherwise honour upstream.gitattributes export-ignore / export-subst. $GIT_DIR/info/attributes wins.
  mkdir -p "$CACHE/info"
  printf '%s\n' '# written by scripts/lib.sh (ensure_cache)' '* -export-ignore -export-subst' > "$CACHE/info/attributes"
  # patches/.rr-cache is committed: automatic `git gc` must never expire recorded resolutions (default 60 days).
  git -C "$CACHE" config gc.rerereResolved 36500
  # Mirror semantics: refs/heads/* follow upstream on every fetch. `git clone --bare` writes them only once, so a
  # bare branch name (update-upstream.sh main) would otherwise resolve to the clone-time commit forever.
  for attempt in 1 2 3; do
    git -C "$CACHE" fetch -q --tags --force --prune "$UPSTREAM_URL" \
      '+refs/heads/*:refs/heads/*' '+refs/heads/*:refs/remotes/upstream/*' && return 0
    warn "fetch failed (attempt $attempt)"; sleep $((attempt * 5))
  done
  die "could not fetch $UPSTREAM_URL"
}

# Version of a tree's pubspec (e.g. 2.0.0+39).
pubspec_version() { sed -n 's/^version:[[:space:]]*//p' "${1:-$UPSTREAM_DIR}/pubspec.yaml" | head -n1 | tr -d '\r'; }

# Toolchain discovery (installs nothing; see scripts/bootstrap-toolchain.sh).
setup_toolchain_env() {
  local env_file="${BACKSTAGE_TOOLCHAIN_ENV:-$HOME/.backstage-toolchain.env}" candidate
  # shellcheck disable=SC1090
  [ -f "$env_file" ] && . "$env_file"
  if [ -z "${ANDROID_HOME:-}" ]; then
    for candidate in "${ANDROID_SDK_ROOT:-}" /home/user/android-sdk "$HOME/Android/Sdk" "$HOME/android-sdk"; do
      [ -n "$candidate" ] && [ -d "$candidate" ] && { ANDROID_HOME="$candidate"; break; }
    done
  fi
  [ -n "${ANDROID_HOME:-}" ] || die "Android SDK not found: set ANDROID_HOME or run scripts/bootstrap-toolchain.sh"
  export ANDROID_HOME ANDROID_SDK_ROOT="$ANDROID_HOME"
  if ! command -v flutter >/dev/null 2>&1; then
    for candidate in "${FLUTTER_ROOT:-}" /home/user/flutter "$HOME/flutter"; do
      [ -n "$candidate" ] && [ -x "$candidate/bin/flutter" ] && { PATH="$candidate/bin:$PATH"; break; }
    done
  fi
  command -v flutter >/dev/null 2>&1 || die "flutter not found: put it on PATH or run scripts/bootstrap-toolchain.sh"
  FLUTTER_ROOT="$(cd "$(dirname "$(readlink -f "$(command -v flutter)")")/.." && pwd -P)"
  export FLUTTER_ROOT PATH FLUTTER_SUPPRESS_ANALYTICS=true CI="${CI:-}"
  # Patience with Maven Central 429s. Heap sizes come from ~/.gradle/gradle.properties when present
  # (user-home properties win over Dextop's -Xmx8G); otherwise a 4 GB default.
  if [ -z "${GRADLE_OPTS:-}" ]; then
    GRADLE_OPTS='-Dorg.gradle.internal.repository.max.tentatives=10 -Dorg.gradle.internal.repository.initial.backoff=1000'
    grep -qs '^org.gradle.jvmargs' "${GRADLE_USER_HOME:-$HOME/.gradle}/gradle.properties" ||
      GRADLE_OPTS+=' -Dorg.gradle.jvmargs=-Xmx4g\ -XX:MaxMetaspaceSize=1g'
  fi
  export GRADLE_OPTS
}

# heavy CMD... - run a memory-hungry build step, serialised through $BACKSTAGE_BUILD_LOCK when set.
heavy() {
  if [ -n "${BACKSTAGE_BUILD_LOCK:-}" ] && command -v flock >/dev/null 2>&1; then
    log "waiting for build lock $BACKSTAGE_BUILD_LOCK"
    flock "$BACKSTAGE_BUILD_LOCK" "$@"
  else
    "$@"
  fi
}
