#!/usr/bin/env bash
# Update OMP pins, SHA-256s and byte-identical omp-termux vendor files. No GitHub API or git required.
#
#   scripts/update-omp-termux.sh [--omp VER|latest] [--bun VER] [--bootstrap TAG] [--commit SHA]
# Defaults: newest omp-termux release, main commit, newest bun (must meet omp engines.bun), newest bootstrap.
# Downloads are retained once in.cache/omp; no app build or downloaded installer is executed.
. "$(dirname "$0")/lib.sh"
. "$ROOT/scripts/lib/omp.sh"
OMP_TERMUX_REPO=https://github.com/hmeqo/omp-termux
OMP_VERSION=latest BUN_VERSION=latest TERMUX_BOOTSTRAP_TAG=latest OMP_TERMUX_COMMIT=main
while (($#)); do
  case "$1" in
    --omp|--bun|--bootstrap|--commit)
      (($# >= 2)) || die "$1 needs a value"
      case "$1" in
        --omp) OMP_VERSION=$2 ;; --bun) BUN_VERSION=$2 ;;
        --bootstrap) TERMUX_BOOTSTRAP_TAG=$2 ;; --commit) OMP_TERMUX_COMMIT=$2 ;;
      esac
      shift 2 ;;
    -h|--help) awk 'NR > 1 { if (!/^#/) exit; sub(/^# ?/, ""); print }' "$0"; exit 0 ;;
    *) die "unknown argument $1" ;;
  esac
done
mkdir -p "$OMP_CACHE"
exec 9>"$OMP_CACHE/.lock"
flock 9
scratch=$(mktemp -d "$OMP_CACHE/update.XXXXXX")
trap 'rm -rf "$scratch"' EXIT
latest_tag() { # follow releases/latest redirects, including percent-encoded bootstrap +
  local url
  url=$(curl -fsSL --retry 3 --proto '=https' --proto-redir '=https' -o /dev/null -w '%{url_effective}' "$1/releases/latest") ||
    die "cannot resolve latest release of $1"
  python3 -I -c 'import sys,urllib.parse; u=urllib.parse.urlparse(sys.argv[1]); assert "/releases/tag/" in u.path, u.path; print(urllib.parse.unquote(u.path.rsplit("/",1)[1]))' "$url"
}
[[ "$OMP_VERSION" != latest ]] || OMP_VERSION=$(latest_tag "$OMP_TERMUX_REPO")
OMP_VERSION=${OMP_VERSION#omp-}
[[ "$BUN_VERSION" != latest ]] || BUN_VERSION=$(latest_tag https://github.com/oven-sh/bun)
BUN_VERSION=${BUN_VERSION#bun-v}
[[ "$TERMUX_BOOTSTRAP_TAG" != latest ]] || TERMUX_BOOTSTRAP_TAG=$(latest_tag https://github.com/termux/termux-packages)
[[ "$OMP_VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "invalid omp version: $OMP_VERSION"
[[ "$BUN_VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "invalid bun version: $BUN_VERSION"
[[ "$TERMUX_BOOTSTRAP_TAG" =~ ^bootstrap-[A-Za-z0-9._+-]+$ ]] || die "invalid bootstrap tag: $TERMUX_BOOTSTRAP_TAG"
if [[ "$OMP_TERMUX_COMMIT" == main ]]; then
  curl -fsSL --retry 3 "$OMP_TERMUX_REPO/commits/main.atom" -o "$scratch/main.atom"
  OMP_TERMUX_COMMIT=$(python3 -I -c 'import re,sys; s=open(sys.argv[1]).read(); m=re.search(r"<id>tag:github.com,2008:Grit::Commit/([0-9a-f]{40})</id>",s); assert m, "cannot resolve main commit"; print(m[1])' "$scratch/main.atom")
fi
[[ "$OMP_TERMUX_COMMIT" =~ ^[0-9a-f]{40}$ ]] || die "--commit must be a full commit SHA"
curl -fsSL --retry 3 "https://registry.npmjs.org/@oh-my-pi/pi-coding-agent/$OMP_VERSION" -o "$scratch/npm.json" ||
  die "omp $OMP_VERSION is not published on npm"
python3 -I "$OMP_HELPER" floor --version "$BUN_VERSION" --metadata "$scratch/npm.json" || die "incompatible bun pin"
# The release asset download is also the release-existence check: npm alone does not imply Android support.
omp_urls
omp_download "$OMP_ADDON_URL" "$OMP_ADDON_FILE"
omp_download "$BUN_ANDROID_URL" "$BUN_ANDROID_FILE"
omp_download "$BUN_HOST_URL" "$BUN_HOST_FILE"
omp_download "$TERMUX_BOOTSTRAP_URL" "$TERMUX_BOOTSTRAP_FILE"
# Keep the shipped license texts synchronized with the selected release tags too.
mkdir -p "$scratch/licenses"
curl -fsSL --retry 3 "https://raw.githubusercontent.com/can1357/oh-my-pi/v$OMP_VERSION/LICENSE" -o "$scratch/licenses/omp-LICENSE"
curl -fsSL --retry 3 "https://raw.githubusercontent.com/oven-sh/bun/bun-v$BUN_VERSION/LICENSE.md" -o "$scratch/licenses/bun-LICENSE.md"
mkdir -p "$scratch/vendor/bin"
for path in bin/omp-termux install.sh LICENSE README.md; do
  curl -fsSL --retry 3 "https://raw.githubusercontent.com/hmeqo/omp-termux/$OMP_TERMUX_COMMIT/$path" -o "$scratch/vendor/$path" ||
    die "could not vendor $path at $OMP_TERMUX_COMMIT"
done
{
  printf '# Vendored from %s at commit %s; generated by scripts/update-omp-termux.sh.\n' "$OMP_TERMUX_REPO" "$OMP_TERMUX_COMMIT"
  printf 'OMP_TERMUX_REPO=%s\nOMP_TERMUX_COMMIT=%s\nOMP_VERSION=%s\n' "$OMP_TERMUX_REPO" "$OMP_TERMUX_COMMIT" "$OMP_VERSION"
  printf 'OMP_ADDON_SHA256=%s\nBUN_VERSION=%s\n' "$(sha256sum "$OMP_ADDON_FILE" | cut -d' ' -f1)" "$BUN_VERSION"
  printf 'BUN_ANDROID_SHA256=%s\nBUN_HOST_SHA256=%s\n' "$(sha256sum "$BUN_ANDROID_FILE" | cut -d' ' -f1)" "$(sha256sum "$BUN_HOST_FILE" | cut -d' ' -f1)"
  printf 'TERMUX_BOOTSTRAP_TAG=%s\nTERMUX_BOOTSTRAP_SHA256=%s\n' "$TERMUX_BOOTSTRAP_TAG" "$(sha256sum "$TERMUX_BOOTSTRAP_FILE" | cut -d' ' -f1)"
} > "$scratch/vendor/UPSTREAM.env"
python3 -I "$OMP_HELPER" pins --pins "$scratch/vendor/UPSTREAM.env" >/dev/null
mkdir -p "$ROOT/upstream/omp-termux/bin"
for path in bin/omp-termux install.sh LICENSE README.md UPSTREAM.env; do
  cp "$scratch/vendor/$path" "$ROOT/upstream/omp-termux/$path"
done
chmod +x "$ROOT/upstream/omp-termux/bin/omp-termux" "$ROOT/upstream/omp-termux/install.sh"
mkdir -p "$ROOT/licenses/texts/omp"
cp "$scratch/licenses/omp-LICENSE" "$ROOT/licenses/texts/omp/LICENSE"
cp "$scratch/licenses/bun-LICENSE.md" "$ROOT/licenses/texts/omp/bun-LICENSE.md"
log "updated upstream/omp-termux (omp $OMP_VERSION, bun $BUN_VERSION, $TERMUX_BOOTSTRAP_TAG)"
cat "$OMP_PINS"
